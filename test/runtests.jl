using CodecXz
using TranscodingStreams: TranscodingStreams
using TestsForCodecPackages
using Test

include("seekable.jl")

@testset "Xz Codec" begin
    codec = XzCompressor()
    @test codec isa XzCompressor
    @test occursin(r"^(CodecXz\.)?XzCompressor\(level=\d, check=\d+, threads=\d+\)$", sprint(show, codec))
    @test CodecXz.initialize(codec) === nothing
    @test CodecXz.finalize(codec) === nothing

    codec = XzDecompressor()
    @test codec isa XzDecompressor
    @test occursin(r"^(CodecXz\.)?XzDecompressor\(memlimit=\d+, flags=\d+\)$", sprint(show, codec))
    @test CodecXz.initialize(codec) === nothing
    @test CodecXz.finalize(codec) === nothing

    # Generated by `lzma.compress(b"foo")` on CPython 3.5.2.
    data = Vector(b"\xfd7zXZ\x00\x00\x04\xe6\xd6\xb4F\x02\x00!\x01\x16\x00\x00\x00t/\xe5\xa3\x01\x00\x02foo\x00\x00X\x15\xa9{,\xe6,\x98\x00\x01\x1b\x03\x0b/\xb9\x10\x1f\xb6\xf3}\x01\x00\x00\x00\x00\x04YZ")
    @test read(XzDecompressorStream(IOBuffer(data))) == b"foo"
    @test read(XzDecompressorStream(IOBuffer(vcat(data, data)))) == b"foofoo"
    # corrupt data
    data[[1,3,5]] = b"bug"
    @test_throws ErrorException read(XzDecompressorStream(IOBuffer(data)))

    @test XzCompressorStream <: TranscodingStreams.TranscodingStream
    @test XzDecompressorStream <: TranscodingStreams.TranscodingStream

    test_roundtrip_read(XzCompressorStream, XzDecompressorStream)
    test_roundtrip_write(XzCompressorStream, XzDecompressorStream)
    test_roundtrip_lines(XzCompressorStream, XzDecompressorStream)
    test_roundtrip_seekstart(XzCompressorStream, XzDecompressorStream)
    test_roundtrip_transcode(XzCompressor, XzDecompressor)

    @test_throws ArgumentError XzCompressor(level=10)
    @test_throws ArgumentError XzDecompressor(memlimit=0)
end

@testset "Encoder options" begin
    Sys.WORD_SIZE == 64 && @test sizeof(CodecXz.LZMAMt) == 128  # sizeof(lzma_mt)
    memusage(codec) = CodecXz.stream_encoder_mt_memusage(codec.options)
    @test XzCompressor().options.threads == 1
    @testset "automatic threads at level $level" for level in (0, 6, 9)
        codec = XzCompressor(; level, threads = 0)
        @test 1 ≤ codec.options.threads ≤ CodecXz.threadcount(0)
        @test codec.options.threads == 1 || memusage(codec) ≤ Sys.total_memory() ÷ 4
    end
    @test XzCompressor(threads = 3).options.threads == 3
    data = rand(UInt8, 300_000)
    @testset "threads=$threads, blocksize=$blocksize" for threads in (1, 4), blocksize in (0, 50_000)
        compressed = transcode(XzCompressor(; threads, blocksize), data)
        @test transcode(XzDecompressor(), compressed) == data
        nblocks = length(XzSeekableStream(IOBuffer(compressed)).codec.index.blocks)
        @test nblocks == if iszero(blocksize) 1 else cld(length(data), blocksize) end
    end
    @testset "a single Block is written as input arrives" begin
        sink = IOBuffer()
        stream = XzCompressorStream(sink)
        write(stream, rand(UInt8, 4 * 2^20))
        @test position(sink) > 2^20
        close(stream)
    end
    @test_throws ArgumentError XzCompressor(threads = -1)
    @test_throws ArgumentError XzCompressor(threads = CodecXz.LZMA_THREADS_MAX + 1)
    @test_throws ArgumentError XzCompressor(blocksize = -1)
    @test_throws ArgumentError XzCompressor(blocksize = CodecXz.LZMA_BLOCK_SIZE_MAX + 1)
end
